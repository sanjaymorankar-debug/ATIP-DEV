"""
PostgreSQL support (W38: DBS-05) -- the server database ATIP is moving to.

DATABASE PLAN (2026-10-09): PostgreSQL is the database for the hosted deployment, replacing the
earlier MySQL plan (db/mysql.py is legacy). SQLite remains the default for a local install.

  translate(sql)        SQLite -> PostgreSQL for the dialect ATIP actually uses (measured with
                        db/dialect_scan.py): ? placeholders, INSERT OR IGNORE, INSERT OR REPLACE (as an
                        upsert on the table's primary key), excluded., date(x, '+/-N unit'), GROUP_CONCAT,
                        2-argument MAX / MIN (-> GREATEST / LEAST), LIKE (case-insensitive in SQLite ->
                        ILIKE). PRAGMA and sqlite_master ARE translated, onto information_schema and a
                        catalogue subquery, so the existence checks db/schema.py's migrations rely on work.
                        rowid on an entry-order table becomes its `seq` column (db.backend.ENTRY_ORDER_TABLES).
                        Constructs with no safe automatic translation -- any other rowid, strftime() in SQL --
                        raise UnsupportedSQL naming the construct, so a missed query fails loudly instead of
                        returning something different.
  ddl(sqlite_create)    a CREATE TABLE / INDEX statement in PostgreSQL types (INTEGER PRIMARY KEY
                        AUTOINCREMENT -> BIGINT GENERATED BY DEFAULT AS IDENTITY, REAL -> DOUBLE PRECISION,
                        BLOB -> BYTEA), plus the identity `seq` column on the entry-order tables
  PgConnection          a sqlite3-shaped connection over psycopg 3 (execute / executemany / cursor /
                        fetchone / fetchall / lastrowid / commit / rollback / close, and `with conn:`; rows
                        readable by index AND by column name, like sqlite3.Row), translating every statement on
                        the way through -- and raising the sqlite3 exception classes callers catch rather than
                        psycopg's, which are unrelated to them. See as_sqlite_error(). The session time zone is
                        pinned to UTC, which is what SQLite's CURRENT_TIMESTAMP / date('now') mean.

Activation (db/schema.pg_runtime_url): ATIP_DATABASE_URL=postgresql://user:pass@host:5432/atip plus
config.json "database": {"backend": "postgresql", "allow_experimental": true}. Both are required.
Requires `pip install "psycopg[binary]"` (in requirements.txt).
"""

