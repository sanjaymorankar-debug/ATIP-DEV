class UnsupportedSQL(ValueError):
    pass


_UNSUPPORTED = [(re.compile(r"^\s*PRAGMA\b", re.I), "PRAGMA"), (re.compile(r"\bsqlite_master\b", re.I), "sqlite_master"),
                (re.compile(r"\browid\b", re.I), "rowid"), (re.compile(r"\bstrftime\s*\(", re.I), "strftime()")]

# sqlite_master as PostgreSQL sees it (type, name, tbl_name, sql) -- catalog queries run unchanged
_SQLITE_MASTER = (
    "(SELECT 'table' AS type, table_name AS name, table_name AS tbl_name, CAST(NULL AS text) AS sql "
    "FROM information_schema.tables WHERE table_schema=current_schema() AND table_type='BASE TABLE' "
    "UNION ALL SELECT 'view', table_name, table_name, view_definition FROM information_schema.views "
    "WHERE table_schema=current_schema() "
    "UNION ALL SELECT 'index', indexname, tablename, indexdef FROM pg_indexes WHERE schemaname=current_schema() "
    "UNION ALL SELECT DISTINCT 'trigger', trigger_name, event_object_table, CAST(NULL AS text) "
    "FROM information_schema.triggers WHERE trigger_schema=current_schema()) AS sqlite_master_pg")


def _table_info(t):
    pk = ("SELECT kcu.column_name FROM information_schema.table_constraints tc JOIN information_schema.key_column_usage "
          "kcu ON tc.constraint_name=kcu.constraint_name AND tc.table_schema=kcu.table_schema WHERE "
          f"tc.table_schema=current_schema() AND tc.table_name='{t}' AND tc.constraint_type='PRIMARY KEY'")
    return ("SELECT ordinal_position-1 AS cid, column_name AS name, upper(data_type) AS type, "
            "CASE WHEN is_nullable='NO' THEN 1 ELSE 0 END AS notnull, column_default AS dflt_value, "
            f"CASE WHEN column_name IN ({pk}) THEN 1 ELSE 0 END AS pk FROM information_schema.columns "
            f"WHERE table_schema=current_schema() AND table_name='{t}' ORDER BY ordinal_position")


def _catalog(sql):
    """PRAGMAs ATIP uses -> PostgreSQL equivalents (or harmless no-ops); None if not one of them."""
    m = re.match(r"\s*PRAGMA\s+table_info\s*\(\s*[\"']?(\w+)[\"']?\s*\)\s*;?\s*$", sql, re.I)
    if m:
        return _table_info(m.group(1))
    if re.match(r"\s*PRAGMA\s+(busy_timeout|foreign_keys|synchronous|cache_size)\b", sql, re.I):
        return "SELECT 1"
    if re.match(r"\s*PRAGMA\s+journal_mode\b", sql, re.I):
        return "SELECT 'wal' AS journal_mode"
    if re.match(r"\s*PRAGMA\s+(integrity_check|quick_check)\s*;?\s*$", sql, re.I):
        return "SELECT 'ok' AS integrity_check"
    return None


def _bool_aggs(sql):
    """SUM / AVG / TOTAL / MIN / MAX of a comparison (SQLite booleans are 0/1) -> SUM(CAST((cmp) AS INT)).
    Two-argument MAX / MIN have already become GREATEST / LEAST, so a MAX( or MIN( left here is the
    aggregate."""
    out, i = [], 0
    pat = re.compile(r"\b(SUM|AVG|TOTAL|MIN|MAX)\s*\(", re.I)
    cmp_rx = re.compile(r"\bIS\s+(NOT\s+)?NULL\b|<>|!=|<=|>=|[<>=]|\bLIKE\b|\bIN\b", re.I)
    while True:
        m = pat.search(sql, i)
        if not m:
            out.append(sql[i:])
            return "".join(out)
        depth, j = 1, m.end()
        while j < len(sql) and depth:
            depth += sql[j] == "("
            depth -= sql[j] == ")"
            j += 1
        arg = sql[m.end():j - 1]
        flat = arg                                            # only top-level comparisons count
        while re.search(r"\([^()]*\)", flat):
            flat = re.sub(r"\([^()]*\)", "", flat)
        out.append(sql[i:m.start()])
        if cmp_rx.search(flat) and not re.match(r"\s*(CASE|DISTINCT)\b", arg, re.I):
            fn = "SUM" if m.group(1).upper() == "TOTAL" else m.group(1)
            out.append(f"{fn}(CAST(({_bool_aggs(arg)}) AS INT))")
        else:
            out.append(m.group(0) + _bool_aggs(arg) + ")")
        i = j
_UNITS = {"day": "day", "days": "day", "month": "month", "months": "month", "year": "year", "years": "year",
          "hour": "hour", "hours": "hour", "minute": "minute", "minutes": "minute"}


def _split_strings(sql):
    """[(is_string_literal, text)] so rewrites never touch quoted text."""
    out, i, buf = [], 0, []
    while i < len(sql):
        ch = sql[i]
        if ch == "'":
            if buf:
                out.append((False, "".join(buf)))
                buf = []
            j = i + 1
            while j < len(sql):
                if sql[j] == "'" and (j + 1 >= len(sql) or sql[j + 1] != "'"):
                    break
                j += 2 if sql[j] == "'" else 1
            out.append((True, sql[i:j + 1]))
            i = j + 1
            continue
        buf.append(ch)
        i += 1
    if buf:
        out.append((False, "".join(buf)))
    return out


def _call_args(sql, open_at):
    """sql[open_at] is '(' -> (index after the matching ')', [top-level arguments]).
    String literals are skipped, so a comma or parenthesis inside quotes is data."""
    depth, i, start, args = 1, open_at + 1, open_at + 1, []
    while i < len(sql):
        c = sql[i]
        if c == "'":
            i += 1
            while i < len(sql) and not (sql[i] == "'" and sql[i + 1:i + 2] != "'"):
                i += 2 if sql[i] == "'" else 1
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                args.append(sql[start:i])
                return i + 1, args
        elif c == "," and depth == 1:
            args.append(sql[start:i])
            start = i + 1
        i += 1
    raise UnsupportedSQL(f"unbalanced parentheses: {sql.strip()[:120]}")


def _rewrite_calls(sql, names, fn):
    """Replace every call name(args...) outside string literals with fn(name, [args]), innermost
    arguments first. A dotted or longer identifier (x.date(, update_date() is not a call to `name`."""
    rx = re.compile(r"(?<![\w.\"])(" + "|".join(names) + r")\s*\(", re.I)
    lit = [False] * len(sql)
    pos = 0
    for s, p in _split_strings(sql):
        if s:
            lit[pos:pos + len(p)] = [True] * len(p)
        pos += len(p)
    out, i = [], 0
    for m in rx.finditer(sql):
        if m.start() < i or lit[m.start()]:
            continue
        end, args = _call_args(sql, m.end() - 1)
        args = [_rewrite_calls(a, names, fn).strip() for a in args]
        out.append(sql[i:m.start()])
        out.append(fn(m.group(1).lower(), args))
        i = end
    out.append(sql[i:])
    return "".join(out)


_TRUNC = {"start of day": "day", "start of month": "month", "start of year": "year"}


def _sqlite_fn(name, args):
    """SQLite scalar functions PostgreSQL lacks or types differently.

    date / datetime / time / julianday with SQLite modifiers. 'now' is UTC in SQLite;
    PgConnection sets the session TimeZone to UTC, so LOCALTIMESTAMP and CURRENT_DATE are
    the same instant. A literal '+N unit' modifier becomes an INTERVAL, 'start of
    day|month|year' a date_trunc, and a non-literal modifier (a parameter or an expression
    such as '+' || n || ' minutes') a CAST to interval -- the text SQLite accepts for those
    is valid interval input. Any other literal modifier ('weekday 1', 'localtime', ...)
    raises UnsupportedSQL rather than meaning something else.

    round(x, n): PostgreSQL has round(numeric, int) only; SQLite's always returns a REAL.
    substr(x, ...): SQLite works on the text of any value (a TIMESTAMP column included);
    PostgreSQL only on text.
    """
    if name == "round":
        if len(args) == 2:
            return f"CAST(ROUND(CAST({args[0]} AS numeric), {args[1]}) AS double precision)"
        return f"ROUND({', '.join(args)})"
    if name == "substr":
        return f"substr(CAST({args[0]} AS text), {', '.join(args[1:])})"
    if not args:
        raise UnsupportedSQL(f"{name}() without arguments")
    base, mods = args[0], args[1:]
    now = base.lower() == "'now'"
    if name == "date" and not mods:
        return "CURRENT_DATE" if now else f"CAST({base} AS date)"
    if name == "date":
        expr = "CURRENT_DATE" if now else f"CAST({base} AS date)"
    else:
        expr = "LOCALTIMESTAMP" if now else f"CAST({base} AS timestamp)"
    for m in mods:
        lit = re.fullmatch(r"'\s*([-+])\s*(\d+(?:\.\d+)?)\s+([a-z]+)\s*'", m, re.I)
        if lit:
            u = _UNITS.get(lit.group(3).lower())
            if not u:
                raise UnsupportedSQL(f"date modifier unit {lit.group(3)!r}")
            expr = f"{expr} {lit.group(1)} INTERVAL '{lit.group(2)} {u}'"
        elif re.fullmatch(r"'(?:[^']|'')*'", m):
            t = _TRUNC.get(m.strip("'").strip().lower())
            if not t:
                raise UnsupportedSQL(f"{name}() modifier {m} has no automatic PostgreSQL translation")
            expr = f"date_trunc('{t}', {expr})"
        else:
            expr = f"{expr} + CAST({m} AS interval)"
    if name == "date":
        return f"CAST({expr} AS date)"
    if name == "datetime":
        return f"CAST({expr} AS timestamp(0))"
    if name == "time":
        return f"CAST({expr} AS time(0))"
    return f"(EXTRACT(EPOCH FROM {expr}) / 86400.0 + 2440587.5)"          # julianday


def _named_params(sql):
    """:name placeholders (sqlite3 named style, used with a dict) -> %(name)s, outside literals.
    `::type` casts are not placeholders."""
    return "".join(p if s else re.sub(r"(?<![:\w]):([A-Za-z_]\w*)", r"%(\1)s", p) for s, p in _split_strings(sql))


def _greatest(sql):
    """MAX(a, b) / MIN(a, b) with a top-level comma -> GREATEST / LEAST (aggregates untouched)."""
    out, i = [], 0
    pat = re.compile(r"\b(MAX|MIN)\s*\(", re.I)
    while True:
        m = pat.search(sql, i)
        if not m:
            out.append(sql[i:])
            return "".join(out)
        depth, j, comma = 1, m.end(), False
        while j < len(sql) and depth:
            c = sql[j]
            if c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
            elif c == "," and depth == 1:
                comma = True
            j += 1
        out.append(sql[i:m.start()])
        out.append(("GREATEST(" if m.group(1).upper() == "MAX" else "LEAST(") if comma else m.group(0))
        i = m.end()


def _qualify_upsert(sql, table, cols):
    """In ON CONFLICT ... DO UPDATE SET a=a+excluded.a, a bare `a` on the right is ambiguous in
    PostgreSQL (target row or excluded row?); SQLite means the target row -> `table.a`.

    `cols` arrives after backticks have become double quotes, so a reserved column
    reads as "rows" here. The name is matched with a non-word lookahead rather than
    \b, which cannot match after a closing quote -- it left "rows" unqualified and
    PostgreSQL answered: column reference "rows" is ambiguous.
    """
    m = re.search(r"\bDO\s+UPDATE\s+SET\b", sql, re.I)
    if not m or not cols:
        return sql
    head, tail = sql[:m.end()], sql[m.end():]
    names = "|".join(re.escape(c) for c in sorted(cols, key=len, reverse=True))
    out, depth, start, parts = [], 0, 0, []
    for i, ch in enumerate(tail):                     # split assignments on top-level commas
        depth += ch == "("
        depth -= ch == ")"
        if ch == "," and depth == 0:
            parts.append(tail[start:i])
            start = i + 1
    parts.append(tail[start:])
    for p in parts:
        if "=" in p:
            lhs, rhs = p.split("=", 1)
            rhs = re.sub(rf"(?<![\w.])({names})(?!\w)(?!\s*\()", rf"{table}.\1", rhs)
            p = lhs + "=" + rhs
        out.append(p)
    return head + ",".join(out)


def translate(sql: str, pk_of=None) -> str:
    """SQLite SQL -> PostgreSQL. pk_of(table) -> [[key columns], ...] (primary key and UNIQUE
    constraints) is needed for INSERT OR REPLACE: SQLite replaces on ANY unique key, so the key used
    is the first one the inserted columns cover (a surrogate id that is not inserted cannot clash)."""
    cat = _catalog(sql)
    if cat is not None:
        return cat
    if re.search(r"\bsqlite_master\b", sql, re.I):            # code parts only, never inside a literal
        sql = "".join(p if s else re.sub(r"\bsqlite_master\b", _SQLITE_MASTER, p, flags=re.I)
                      for s, p in _split_strings(sql))
    # rowid as an ORDER BY tie-breaker (entry order) -> ctid. Valid because every such use is on an
    # append-only table (perf_ledger, ml_dl_benefit: no UPDATE / DELETE, so tuples never move); any
    # other rowid use still fails below.
    ob = re.search(r"\bORDER\s+BY\b(?!.*\bORDER\s+BY\b)", sql, re.I | re.S)
    if ob and re.search(r"\browid\b", sql[ob.end():], re.I) and not re.search(r"\browid\b", sql[:ob.start()], re.I):
        sql = sql[:ob.end()] + re.sub(r"\b((?:\w+\.)?)rowid\b", r"\1ctid", sql[ob.end():], flags=re.I)
    for rx, name in _UNSUPPORTED:
        if rx.search("".join(p for s, p in _split_strings(sql) if not s)):
            raise UnsupportedSQL(f"{name} has no automatic PostgreSQL translation: {sql.strip()[:120]}")
    # Backtick-quoted identifiers. ATIP's shared SQL quotes some columns (signal, key,
    # rank, rows, change, trigger) with backticks -- written for the MySQL backend that
    # was removed on 23 Nov 2026, where they are reserved words. SQLite accepts
    # backticks, PostgreSQL does not, so they become the standard double quote here
    # (new SQL need not use them). Double quoting also makes the name
    # case-sensitive in PostgreSQL -- harmless, as ATIP declares every column in
    # lower case, which is what an unquoted name folds to.
    sql = "".join(p if s else p.replace("`", '"') for s, p in _split_strings(sql))

    parts = _split_strings(sql)
    text = "\x00".join(p for s, p in parts if not s)                    # code only, joined by markers
    strings = [p for s, p in parts if s]
    replace_target = None
    m = re.search(r"\bINSERT\s+OR\s+REPLACE\s+INTO\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(([^)]*)\)", text, re.I)
    if m:
        replace_target = (m.group(1), [c.strip() for c in m.group(2).split(",")])
        text = re.sub(r"\bINSERT\s+OR\s+REPLACE\s+INTO\b", "INSERT INTO", text, flags=re.I)
    ignore = bool(re.search(r"\bINSERT\s+OR\s+IGNORE\s+INTO\b", text, re.I))
    text = re.sub(r"\bINSERT\s+OR\s+IGNORE\s+INTO\b", "INSERT INTO", text, flags=re.I)
    text = re.sub(r"\bGROUP_CONCAT\s*\(\s*(DISTINCT\s+)?([^)]*?)\s*\)",
                  lambda g: f"string_agg({g.group(1) or ''}CAST({g.group(2)} AS text), ',')", text, flags=re.I)
    text = re.sub(r"\bIFNULL\s*\(", "COALESCE(", text, flags=re.I)
    text = re.sub(r"\bNOT\s+LIKE\b", "NOT ILIKE", text, flags=re.I)
    text = re.sub(r"(?<!NOT )\bLIKE\b", "ILIKE", text, flags=re.I)
    text = _greatest(text)
    text = _bool_aggs(text)
    # `IS ?` / `IS NOT ?` -- SQLite's null-safe comparison with a parameter; PostgreSQL's IS takes
    # only NULL / TRUE / FALSE
    text = re.sub(r"\bIS\s+NOT\s+(\?|:[A-Za-z_]\w*)", r"IS DISTINCT FROM \1", text, flags=re.I)
    text = re.sub(r"\bIS\s+(\?|:[A-Za-z_]\w*)", r"IS NOT DISTINCT FROM \1", text, flags=re.I)
    # CURRENT_TIMESTAMP is 'YYYY-MM-DD HH:MM:SS' UTC text in SQLite; LOCALTIMESTAMP(0) in a UTC session
    # is the same value, and has the same text when it lands in a TEXT column
    text = re.sub(r"\bCURRENT_TIMESTAMP\b", "LOCALTIMESTAMP(0)", text, flags=re.I)
    # rejoin with the string literals back in place, then the date() modifiers (they contain literals)
    chunks = text.split("\x00")
    out = []
    for i, ch in enumerate(chunks):
        out.append(ch)
        if i < len(strings):
            out.append(strings[i])
    sql2 = "".join(out)
    sql2 = _rewrite_calls(sql2, ("date", "datetime", "time", "julianday", "round", "substr"), _sqlite_fn)
    # ? -> %s outside literals; every % is doubled, INSIDE literals too (LIKE 'a%'): psycopg parses the
    # whole statement for placeholders when parameters are passed, and PgConnection always passes them
    sql2 = "".join(p.replace("%", "%%") if s else p.replace("%", "%%").replace("?", "%s")
                   for s, p in _split_strings(sql2))
    sql2 = _named_params(sql2)
    if ignore and not re.search(r"\bON\s+CONFLICT\b", sql2, re.I):
        sql2 = sql2.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    if replace_target:
        table, cols = replace_target
        keys = [list(k) for k in (pk_of(table) if pk_of else []) if k]
        if keys and isinstance(keys[0], str):                 # a bare [col, ...] list = one key
            keys = [keys]
        key = next((k for k in keys if set(k) <= set(cols)), None)
        if not key:
            raise UnsupportedSQL(f"INSERT OR REPLACE into {table}: no primary / unique key among the inserted "
                                 f"columns {cols}")
        sets = ", ".join(f"{c}=EXCLUDED.{c}" for c in cols if c not in key)
        sql2 = sql2.rstrip().rstrip(";") + f" ON CONFLICT ({', '.join(key)}) " + (f"DO UPDATE SET {sets}" if sets
                                                                                  else "DO NOTHING")
    else:
        m2 = re.search(r"\bINSERT\s+INTO\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(([^)]*)\)", sql2, re.I)
        if m2:
            sql2 = _qualify_upsert(sql2, m2.group(1), [c.strip() for c in m2.group(2).split(",")])
    return sql2


def ddl(stmt: str) -> str:
    s = stmt
    # backtick-quoted reserved column names (signal, rows, trigger) -> standard double quotes, as
    # translate() already does for queries; PostgreSQL rejects backticks in CREATE TABLE too
    s = "".join(p if q else p.replace("`", '"') for q, p in _split_strings(s))
    # INTEGER PRIMARY KEY is the rowid alias in SQLite: auto-numbered with or without AUTOINCREMENT
    s = re.sub(r"\bINTEGER\s+PRIMARY\s+KEY(\s+AUTOINCREMENT)?\b", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
               s, flags=re.I)
    s = re.sub(r"\bAUTOINCREMENT\b", "", s, flags=re.I)
    # SQLite's CURRENT_TIMESTAMP / datetime('now') default is 'YYYY-MM-DD HH:MM:SS' in UTC.
    # LOCALTIMESTAMP(0) in PgConnection's UTC session is that value -- and that text in a TEXT
    # column, where CURRENT_TIMESTAMP would store '... .123456+00'.
    s = re.sub(r"\(\s*datetime\s*\(\s*'now'\s*\)\s*\)|\bdatetime\s*\(\s*'now'\s*\)|\bCURRENT_TIMESTAMP\b",
               "LOCALTIMESTAMP(0)", s, flags=re.I)
    s = re.sub(r"\(\s*date\s*\(\s*'now'\s*\)\s*\)|\bdate\s*\(\s*'now'\s*\)", "CURRENT_DATE", s, flags=re.I)
    s = re.sub(r"\bWITHOUT\s+ROWID\b", "", s, flags=re.I)
    s = re.sub(r"\s+COLLATE\s+NOCASE\b", "", s, flags=re.I)
    s = re.sub(r"\bREAL\b", "DOUBLE PRECISION", s, flags=re.I)
    s = re.sub(r"\bBLOB\b", "BYTEA", s, flags=re.I)
    s = re.sub(r"\bINTEGER\b", "BIGINT", s, flags=re.I)
    s = re.sub(r"\bBOOL(EAN)?\b", "SMALLINT", s, flags=re.I)     # SQLite stores 0/1 and the code compares with 1
    s = re.sub(r"\bDATETIME\b", "TIMESTAMP", s, flags=re.I)
    s = re.sub(r"CHECK\s*\(\s*id\s*=\s*1\s*\)", "CHECK (id = 1)", s, flags=re.I)
    return s


APPEND_ONLY_FN = ("CREATE OR REPLACE FUNCTION atip_append_only() RETURNS trigger LANGUAGE plpgsql AS $$ "
                  "BEGIN RAISE EXCEPTION '%', TG_ARGV[0]; END $$")


def trigger_ddl(sql: str) -> str:
    """ATIP's SQLite triggers are all append-only guards:
         BEFORE UPDATE|DELETE ON t [WHEN cond] BEGIN SELECT RAISE(ABORT, 'msg'); END
    -> a PostgreSQL row trigger calling atip_append_only('msg') (APPEND_ONLY_FN, created first).
    Anything else raises UnsupportedSQL rather than being dropped silently."""
    m = re.match(r"\s*CREATE\s+TRIGGER\s+(?:IF\s+NOT\s+EXISTS\s+)?(\w+)\s+(BEFORE|AFTER)\s+(UPDATE|DELETE|INSERT)\s+"
                 r"ON\s+(\w+)\s+(?:FOR\s+EACH\s+ROW\s+)?(?:WHEN\s+(.+?)\s+)?BEGIN\s+SELECT\s+RAISE\s*\(\s*ABORT\s*,\s*"
                 r"'((?:[^']|'')*)'\s*\)\s*;\s*END\s*;?\s*$", sql, re.I | re.S)
    if not m:
        raise UnsupportedSQL(f"trigger is not an append-only guard: {' '.join(sql.split())[:120]}")
    name, when, event, table, cond, msg = m.groups()
    cond_sql = f" WHEN ({cond})" if cond else ""
    return (f"CREATE TRIGGER {name} {when.upper()} {event.upper()} ON {table} FOR EACH ROW{cond_sql} "
            f"EXECUTE FUNCTION atip_append_only('{msg}')")


def keys_from_ddl(stmts) -> dict:
    """{table: [[key columns], ...]} from CREATE TABLE / CREATE UNIQUE INDEX statements (PK first)."""
    keys: dict = {}
    for s in stmts:
        m = re.search(r"CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?([A-Za-z_]\w*)\s*\((.*)\)", s, re.I | re.S)
        if m:
            t, body = m.group(1), m.group(2)
            ks = keys.setdefault(t, [])
            for c in re.finditer(r"PRIMARY\s+KEY\s*\(([^)]*)\)", body, re.I):
                ks.insert(0, [x.strip() for x in c.group(1).split(",")])
            for c in re.finditer(r"(?:^|,)\s*([A-Za-z_]\w*)\s+[^,]*?\bPRIMARY\s+KEY\b", body, re.I):
                ks.insert(0, [c.group(1)])
            for c in re.finditer(r"\bUNIQUE\s*\(([^)]*)\)", body, re.I):
                ks.append([x.strip() for x in c.group(1).split(",")])
            for c in re.finditer(r"(?:^|,)\s*([A-Za-z_]\w*)\s+\w+[^,(]*?\bUNIQUE\b(?!\s*\()", body, re.I):
                ks.append([c.group(1)])
            continue
        m = re.search(r"CREATE\s+UNIQUE\s+INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?\w+\s+ON\s+([A-Za-z_]\w*)\s*\(([^)]*)\)",
                      s, re.I)
        if m:
            keys.setdefault(m.group(1), []).append([x.strip().split()[0] for x in m.group(2).split(",")])
    return keys


# ── a sqlite3-shaped connection over psycopg 3 ────────────────────────────
class Row(tuple):
    """Index and name access, like sqlite3.Row."""
    def __new__(cls, values, names):
        r = super().__new__(cls, values)
        r._names = names
        return r

    def __getitem__(self, k):
        if isinstance(k, str):
            return super().__getitem__(self._names.index(k))
        return super().__getitem__(k)

    def keys(self):
        return list(self._names)


# ── errors: psycopg's exceptions as the sqlite3 ones callers catch ─────────
#
# psycopg and sqlite3 both implement PEP 249, but their hierarchies are
# unrelated, so `except sqlite3.OperationalError` catches nothing psycopg raises.
# ATIP's additive migrations are built on that clause (db/schema.py swallows
# "column already exists" to make ALTER TABLE ADD COLUMN idempotent), so the
# connection has to raise what they catch, exactly as it already answers to `?`
# placeholders and sqlite3.Row.
#
# The rule is simple, because PostgreSQL reports the SQL standard's own SQLSTATE
# and class 23 *is* "integrity constraint violation":
# 23502 not-null, 23503 foreign key, 23505 unique, 23514 check, 23001 restrict,
# 23P01 exclusion. That is exactly the set SQLite raises IntegrityError for, so the
# prefix is the mapping -- no table of codes to fall out of date.
#
# psycopg's own classes cannot be used for this. They are finer-grained than
# sqlite3's (DuplicateColumn, UndefinedTable, SyntaxError) and they sort conditions
# differently again: a duplicate column is DuplicateColumn where SQLite says
# OperationalError, and a CHECK violation is CheckViolation where SQLite says
# IntegrityError. Verified against PostgreSQL 16.14.


def as_sqlite_error(exc: Exception) -> Exception:
    """`exc` as the sqlite3 class SQLite would raise for the same condition.

    `args` is carried over unchanged, so the message reads the way psycopg wrote it
    -- psycopg puts the message in args[0], which is also sqlite3's own
    convention. The SQLSTATE is kept on the result as `.sqlstate` for
    anything that wants to switch on it. Whatever is not a psycopg error is returned
    untouched, which is what keeps UnsupportedSQL and ordinary programming mistakes
    from being disguised as database trouble.
    """
    try:
        import psycopg
    except ImportError:                       # pragma: no cover - PgConnection cannot exist
        return exc
    if not isinstance(exc, psycopg.Error):
        return exc
    sqlstate = getattr(exc, "sqlstate", None) or ""
    cls = sqlite3.IntegrityError if sqlstate.startswith("23") else sqlite3.OperationalError
    args = exc.args
    if sqlstate == "55P03":                   # lock_not_available (lock_timeout): SQLite's busy-timeout error
        args = (f"database is locked ({exc.args[0] if exc.args else 'lock timeout'})",) + tuple(exc.args[1:])
    out = cls(*args).with_traceback(exc.__traceback__)
    out.sqlstate = sqlstate or None
    return out


@contextlib.contextmanager
def sqlite_errors():
    """Re-raise whatever psycopg raises inside as the sqlite3 class SQLite would."""
    try:
        yield
    except Exception as e:
        translated = as_sqlite_error(e)
        if translated is e:
            raise
        raise translated from e


class _Cursor:
    def __init__(self, cur, lastrowid=None):
        self._c = cur
        self.lastrowid = lastrowid

    def _wrap(self, r):
        if r is None:
            return None
        names = [d.name for d in self._c.description] if self._c.description else []
        return Row(r, names)

    def fetchone(self):
        with sqlite_errors():
            if self._c.description is None:                         # INSERT / UPDATE: None, as in sqlite3
                return None
            return self._wrap(self._c.fetchone())

    def fetchall(self):
        with sqlite_errors():
            if self._c.description is None:                         # INSERT / UPDATE: no rows, as in sqlite3
                return []
            return [self._wrap(r) for r in self._c.fetchall()]

    def fetchmany(self, size=None):
        with sqlite_errors():
            if self._c.description is None:
                return []
            return [self._wrap(r) for r in self._c.fetchmany(size or 1)]

    def __iter__(self):
        return iter(self.fetchall())

    def close(self):
        pass

    @property
    def rowcount(self):
        return self._c.rowcount

    @property
    def description(self):
        return self._c.description


class _Done:
    """An INSERT whose RETURNING row has been read for lastrowid: no rows, like sqlite3's."""
    description = None

    def __init__(self, rowcount):
        self.rowcount = rowcount


class _ConnCursor:
    """conn.cursor(): a sqlite3-style cursor -- execute() returns the cursor itself and the last
    result is read from it. pandas.read_sql works through exactly this (cursor().execute(),
    then .description and .fetchall() on the same object), as does init_db()'s
    conn.cursor().execute(...)."""

    def __init__(self, conn):
        self._conn = conn
        self._last = None

    def execute(self, sql, params=()):
        self._last = self._conn.execute(sql, params)
        return self

    def executemany(self, sql, seq):
        self._last = self._conn.executemany(sql, seq)
        return self

    def fetchone(self):
        return self._last.fetchone() if self._last else None

    def fetchall(self):
        return self._last.fetchall() if self._last else []

    def fetchmany(self, size=None):
        return self._last.fetchmany(size) if self._last else []

    def __iter__(self):
        return iter(self.fetchall())

    def close(self):
        self._last = None

    @property
    def description(self):
        return self._last.description if self._last else None

    @property
    def rowcount(self):
        return self._last.rowcount if self._last else -1

    @property
    def lastrowid(self):
        return self._last.lastrowid if self._last else None


# "End of this day" bounds written for SQLite's TEXT comparison: day + " 99", day + "T99", day + "~"
# sort after every time of that day as text, so `ts < ?` / `date <= ?` with one of them means "up to the
# end of the day". PostgreSQL compares DATE / TIMESTAMP columns as values and rejects them as input
# ("invalid input syntax for type timestamp"). As a parameter they become the last instant of that
# day, which keeps the meaning for both column types: as a DATE it is the day itself.
# Used by quant/microstructure.py, data/order_pressure.py, orders/arms.py and scores/breadth.py.
_EOD_SENTINEL = re.compile(r"^(\d{4}-\d{2}-\d{2})(?: 99|T99|~)$")


def _param(v):
    if isinstance(v, str):
        m = _EOD_SENTINEL.match(v)
        if m:
            return f"{m.group(1)} 23:59:59.999999"
    return v


def _params(p):
    if isinstance(p, dict):
        return {k: _param(v) for k, v in p.items()}
    return tuple(_param(v) for v in (p or ()))


def _register_loaders(conn):
    """Result values as sqlite3 returns them.

    numeric (SUM / AVG of an integer column, ROUND(numeric)) arrives from psycopg as Decimal,
    which does not mix with float (Decimal * float raises TypeError); SQLite returns int or float.
    boolean (a comparison in a SELECT list) arrives as True / False where SQLite returns 1 / 0 --
    and that reaches JSON as true / false. DATE and TIMESTAMP columns already load as
    datetime.date / datetime.datetime, which is what db/schema's PARSE_DECLTYPES converters give."""
    from psycopg.adapt import Loader

    class _Numeric(Loader):
        def load(self, data):
            s = bytes(data).decode()
            if "." in s or "e" in s.lower() or s in ("NaN", "Infinity", "-Infinity"):
                return float(s)
            return int(s)

    class _Bool(Loader):
        def load(self, data):
            return 1 if bytes(data) == b"t" else 0

    conn.adapters.register_loader("numeric", _Numeric)
    conn.adapters.register_loader("bool", _Bool)


# ── SQLite transaction control on PostgreSQL ─────────────────────────────
#
# ATIP starts its check-then-write transactions with SQLite's `BEGIN IMMEDIATE` (ops/jobs.acquire --
# job locks and the scheduler leader lease --, ops/migrations.apply, orders/algo_gtt.place_dummy_buy).
# PostgreSQL has no such statement: until 18 Nov 2026 it was passed through and failed as a syntax error,
# so on the VPS every job lock silently failed open, every Kite-retest dummy buy came back "Busy, try
# again" and any new migration would have been recorded FAILED. IMMEDIATE means "take the database's
# write lock now, waiting up to the busy timeout, else fail with 'database is locked'". The equivalent
# here is one transaction-scoped advisory lock that every BEGIN IMMEDIATE / EXCLUSIVE takes: those
# transactions run one at a time, as in SQLite, and the lock ends with the COMMIT / ROLLBACK. (SQLite
# also makes plain writers wait; on PostgreSQL row locks and unique indexes cover those, and every
# statement in the transaction still sees the latest committed rows -- READ COMMITTED.)
WRITE_LOCK_KEY = 0x4154_4950_5752_4954      # "ATIPWRIT": one key for the whole database, like SQLite's lock
WRITE_LOCK_WAIT_S = 60.0                    # db/schema.BUSY_TIMEOUT_MS: how long SQLite waits for the lock
LOCK_TIMEOUT_S = 60.0                       # LRCA-04: every PostgreSQL lock wait ends here too (SQLite busy timeout)
_TX_CONTROL = re.compile(r"\s*(?:(BEGIN)(?:\s+(DEFERRED|IMMEDIATE|EXCLUSIVE))?|(COMMIT|END)|(ROLLBACK))"
                         r"(?:\s+TRANSACTION)?\s*;?\s*", re.I)
_DML = re.compile(r"\s*(INSERT|UPDATE|DELETE)\b", re.I)


class PgConnection:
    def __init__(self, dsn: str):
        try:
            import psycopg
        except ImportError as e:
            raise RuntimeError('PostgreSQL backend needs: pip install "psycopg[binary]"') from e
        self._conn = psycopg.connect(dsn)
        # SQLite's 'now' and CURRENT_TIMESTAMP are UTC; so is this session (see _sqlite_fn)
        self._conn.execute("SET TimeZone TO 'UTC'")
        # LRCA-04 (19 Nov 2026): SQLite gives up on a lock after its 60 s busy timeout ("database is locked", which
        # the order monitor's RCA-13 fast retry and every lock handler look for); PostgreSQL waits on a row lock for
        # ever, so one connection left in a transaction could hang the single order-monitor thread -- no exits for
        # the rest of the day. Same limit here; as_sqlite_error() words SQLSTATE 55P03 the SQLite way.
        self._conn.execute(f"SET lock_timeout = '{int(LOCK_TIMEOUT_S * 1000)}ms'")
        self._conn.commit()
        _register_loaders(self._conn)
        self._pk = {}
        self._ident = {}
        self.total_changes = 0
        self.row_factory = None                                     # accepted for sqlite3 compatibility
        self._dirty = False             # a write since the last commit / rollback (sqlite3's open transaction)
        self.write_lock_wait = WRITE_LOCK_WAIT_S

    def pk_of(self, table):
        """[[columns] per unique index], primary key first."""
        if table in self._pk:
            return self._pk[table]
        with sqlite_errors():
            cur = self._conn.execute(
                "SELECT i.indexrelid, i.indisprimary, a.attname FROM pg_index i "
                "JOIN pg_attribute a ON a.attrelid=i.indrelid AND a.attnum=ANY(i.indkey) "
                "WHERE i.indrelid=%s::regclass AND i.indisunique ORDER BY i.indisprimary DESC, i.indexrelid",
                (table,))
            keys: dict = {}
            for idx, _prim, col in cur.fetchall():
                keys.setdefault(idx, []).append(col)
        self._pk[table] = list(keys.values())
        return self._pk[table]

    @staticmethod
    def _is_ddl(sql):
        return sql.lstrip().upper().startswith(("CREATE ", "ALTER ", "DROP "))

    def identity_of(self, table):
        """The table's identity column (INTEGER PRIMARY KEY in SQLite, i.e. the rowid alias), or None."""
        if table not in self._ident:
            with sqlite_errors():
                r = self._conn.execute("SELECT attname FROM pg_attribute WHERE attrelid=to_regclass(%s) "
                                       "AND attidentity<>'' AND NOT attisdropped", (table,)).fetchone()
            self._ident[table] = r[0] if r else None
        return self._ident[table]

    def _statement(self, run):
        """Run one statement with SQLite's failure semantics.

        In SQLite a failed statement fails alone; the open transaction carries on, and ATIP relies
        on that (ALTER TABLE ADD COLUMN that may already exist, a probe of a table that may not).
        PostgreSQL aborts the whole transaction instead -- every later statement then fails with
        "current transaction is aborted" -- so inside a transaction each statement runs under a
        savepoint, and a failure rolls back to it. Outside one there is nothing to protect: the
        failed implicit transaction is rolled back, leaving the connection idle, as in SQLite."""
        from psycopg.pq import TransactionStatus
        in_tx = self._conn.info.transaction_status == TransactionStatus.INTRANS
        if in_tx:
            self._conn.execute("SAVEPOINT atip_stmt")
        try:
            out = run()
        except Exception:
            if in_tx:
                self._conn.execute("ROLLBACK TO SAVEPOINT atip_stmt")
                self._conn.execute("RELEASE SAVEPOINT atip_stmt")
            else:
                self._conn.rollback()
            raise
        if in_tx:
            self._conn.execute("RELEASE SAVEPOINT atip_stmt")
        return out

    def _vacuum(self):
        """SQLite's VACUUM. PostgreSQL refuses VACUUM inside a transaction block, and psycopg
        opens one implicitly, so it runs in autocommit. Like SQLite, it is an error while a
        transaction is open (db/purge.py commits first)."""
        from psycopg.pq import TransactionStatus
        if self._conn.info.transaction_status != TransactionStatus.IDLE:
            raise sqlite3.OperationalError("cannot VACUUM from within a transaction")
        with sqlite_errors():
            self._conn.autocommit = True
            try:
                self._conn.execute("VACUUM (ANALYZE)")
            finally:
                self._conn.autocommit = False
        return _Cursor(_Done(-1))

    def _tx_control(self, m):
        """BEGIN [DEFERRED | IMMEDIATE | EXCLUSIVE] / COMMIT / END / ROLLBACK, as sqlite3 runs them.

        psycopg opens a transaction before the first statement, reads included; Python's sqlite3 opens one
        only before INSERT / UPDATE / DELETE. So a transaction that holds nothing but reads (or DDL, which
        sqlite3 commits as it goes) is one SQLite would not have: it is committed and the BEGIN goes ahead.
        After an uncommitted write SQLite refuses the BEGIN, and so does this. COMMIT / ROLLBACK with no
        transaction open are no-ops."""
        from psycopg.pq import TransactionStatus
        begin, mode, commit, rollback = m.groups()
        if commit:
            self.commit()
        elif rollback:
            self.rollback()
        else:
            if self._conn.info.transaction_status != TransactionStatus.IDLE:
                if self._dirty:
                    raise sqlite3.OperationalError("cannot start a transaction within a transaction")
                self.commit()
            if (mode or "").upper() in ("IMMEDIATE", "EXCLUSIVE"):
                self._write_lock()
        return _Cursor(_Done(-1))

    def _write_lock(self):
        """The database write lock for this transaction (see WRITE_LOCK_KEY): waits up to write_lock_wait
        seconds, then fails the way SQLite does when its busy timeout runs out."""
        import time
        deadline = time.monotonic() + self.write_lock_wait
        with sqlite_errors():
            while not self._conn.execute("SELECT pg_try_advisory_xact_lock(%s)", (WRITE_LOCK_KEY,)).fetchone()[0]:
                if time.monotonic() >= deadline:
                    self._conn.rollback()
                    raise sqlite3.OperationalError("database is locked")
                time.sleep(0.05)

    def execute(self, sql, params=()):
        tx = _TX_CONTROL.fullmatch(sql)
        if tx:
            return self._tx_control(tx)
        # Translation happens outside sqlite_errors(): it touches no server, so a
        # statement this backend cannot express raises UnsupportedSQL rather than
        # arriving disguised as a database error.
        if re.fullmatch(r"\s*VACUUM\s*;?\s*", sql, re.I):
            return self._vacuum()
        if self._is_ddl(sql):                       # untouched by placeholder parsing (trigger bodies use %)
            if re.match(r"\s*CREATE\s+TRIGGER", sql, re.I):
                stmt = sql if re.search(r"\bEXECUTE\s+FUNCTION\b", sql, re.I) else trigger_ddl(sql)
            elif re.match(r"\s*CREATE\s+(OR\s+REPLACE\s+)?FUNCTION", sql, re.I):
                stmt = sql                          # PostgreSQL already (atip_append_only)
            else:
                stmt = ddl(sql)
            self._ident.clear()
            with sqlite_errors():
                return _Cursor(self._statement(lambda: self._conn.execute(stmt)))
        stmt = translate(sql, self.pk_of)
        args = _params(params)
        # sqlite3 fills cursor.lastrowid after an INSERT; PostgreSQL needs RETURNING for it
        ins = re.match(r"\s*INSERT\s+INTO\s+\"?([A-Za-z_]\w*)\"?", stmt, re.I)
        ident = self.identity_of(ins.group(1)) if ins and not re.search(r"\bRETURNING\b", stmt, re.I) else None
        if ident:
            stmt = stmt.rstrip().rstrip(";") + f' RETURNING "{ident}"'
        with sqlite_errors():
            cur = self._statement(lambda: self._conn.execute(stmt, args))
            rowid = None
            if ident:
                rows = cur.fetchall()
                rowid = rows[-1][0] if rows else None
        if _DML.match(stmt):
            self._dirty = True
            if cur.rowcount > 0:
                self.total_changes += cur.rowcount
        return _Cursor(cur, rowid) if not ident else _Cursor(_Done(cur.rowcount), rowid)

    def executemany(self, sql, seq):
        stmt = translate(sql, self.pk_of)
        rows = [_params(p) for p in seq]
        with sqlite_errors():
            cur = self._conn.cursor()
            self._statement(lambda: cur.executemany(stmt, rows))
        if _DML.match(stmt):
            self._dirty = True
        if cur.rowcount > 0:
            self.total_changes += cur.rowcount
        return _Cursor(cur)

    def reset_identity(self, table, column="id"):
        """After a bulk copy with explicit ids, move the identity sequence past MAX(id)."""
        with sqlite_errors():
            self._conn.execute(f"SELECT setval(pg_get_serial_sequence('{table}', '{column}'), "
                               f"COALESCE((SELECT MAX({column}) FROM {table}), 0) + 1, false)")

    @property
    def in_transaction(self) -> bool:
        """sqlite3.Connection.in_transaction: True after a write that is not yet committed. LRCA-10 (19 Nov 2026):
        without it the pre-open gate (ops/preopen_health.py) read False and committed its caller's open
        transaction part-way through on PostgreSQL."""
        return bool(self._dirty)

    def commit(self):
        with sqlite_errors():
            self._conn.commit()
        self._dirty = False

    def rollback(self):
        with sqlite_errors():
            self._conn.rollback()
        self._dirty = False

    def close(self):
        self._conn.close()

    def cursor(self):
        """sqlite3 compatibility: a connection-level cursor that behaves like ours.

        init_db() is hundreds of `conn.cursor().execute(...)` calls, so without this
        the PostgreSQL backend could not create the schema at all -- it failed with
        AttributeError before any SQL was sent.

        It is a separate cursor object rather than the connection itself, so that
        pandas.read_sql -- cursor().execute(), then .description / .fetchall() on that
        same cursor -- works too.
        """
        return _ConnCursor(self)

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        if exc and exc[0]:
            self.rollback()
        else:
            self.commit()
        return False
